/** Dile göre URL öneki: tr → "/", en → "/en/", de → "/de/" */
export function localePath(lang: Lang, path = ''): string {
  const clean = path.replace(/^\/+/, '');
  return lang === defaultLang ? `/${clean}` : `/${lang}/${clean}`;
}

